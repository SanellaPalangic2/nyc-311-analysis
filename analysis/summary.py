"""Stage 4: final summary of the advanced analyses.

Run:  python analysis/summary.py      (seconds; run Stages 1-3 first)

1. Re-renders results/results.md (summary tables + limitations).
2. Writes the "Advanced Analysis" section of README.md between two marker
   comments, so rerunning replaces it instead of adding a second copy.
3. Prints resume-ready numbers and two resume bullets built only from them.

Every number comes from key_numbers(), which reads results/data/*.json.
"""
import results_md
from key_numbers import key_numbers

import common

README = common.PROJECT_ROOT / "README.md"
START = "<!-- ADVANCED-ANALYSIS:START (generated by analysis/summary.py; edit that script, not this text) -->"
END = "<!-- ADVANCED-ANALYSIS:END -->"

# The four figures that tell the story best: what survival analysis changes,
# how much each factor matters, and what the model relies on.
README_FIGURES = [
    ("1a_km_top8_agencies.png", "Kaplan-Meier curves, top 8 agencies"),
    ("1b_median_bias_by_agency.png", "Median with vs without open requests"),
    ("2a_effect_sizes.png", "Effect sizes: agency vs borough vs season"),
    ("3d_permutation_importance.png", "What the prediction model relies on"),
]


def fmt_h(x):
    return "not reached" if x is None else f"{x:,.2f}"


def readme_section(k):
    bias = k["biggest_bias"][0]
    top3 = ", ".join(f"{f} ({d:.4f})" for f, d in k["top3_features"])
    figs = [f'<img src="results/figures/{name}" alt="{alt}" width="100%">'
            for name, alt in README_FIGURES]
    return "\n".join([
        START,
        "## Advanced Analysis",
        "",
        "Three follow-up analyses in [`analysis/`](analysis/), with every number in "
        "[`results/results.md`](results/results.md):",
        "",
        f"- **Survival analysis (lifelines).** Instead of dropping the {k['censored']:,} still-open "
        f"requests, they're treated as *censored* (open for at least as long as observed). The "
        f"overall median moves from {fmt_h(k['overall_closed_only'])} h to "
        f"{fmt_h(k['overall_km'])} h, but the bias is concentrated: {bias['agency']}'s median rises "
        f"from {fmt_h(bias['median_closed_only'])} h to {fmt_h(bias['km_median'])} h "
        f"({bias['difference_pct']:+.2f}%). In a Cox model (concordance "
        f"{k['cox_concordance']:.4f}), "
        + ("agency has by far the largest effects, " if k["cox_agency_dominates"] else "")
        + f"though the proportional hazards assumption fails for "
        f"{k['ph_violating']} of {k['ph_covariates']} covariates, so its hazard ratios are "
        "read as average effects.",
        f"- **Statistical testing.** Kruskal-Wallis effect sizes (epsilon-squared): agency "
        f"{k['eps']['agency']:.4f}, season {k['eps']['season']:.4f}, borough "
        f"{k['eps']['borough']:.4f}. Every p-value is below 1e-300 with "
        f"{k['n_closed']:,} rows, so the effect size is what matters"
        + (f": agency explains {k['eps_ratio_vs_next']:,.1f}x more than the next factor."
           if k["agency_largest_effect"] else ".")
        + f" Bootstrapped 95% CIs ({k['n_boot']:,} resamples) for each agency's median are "
        f"narrow for large agencies; the widest is {k['boot_widest']['agency']} "
        f"({fmt_h(k['boot_widest']['ci_lower'])} - {fmt_h(k['boot_widest']['ci_upper'])} h, "
        f"{k['boot_widest']['n']:,} requests).",
        f"- **Prediction (scikit-learn).** Predicting closure within 7 days from information "
        f"known at filing, trained on Jan-Sep and tested on Oct-Dec 2025: {k['best_model'].lower()} "
        f"reaches ROC AUC {k['best_auc']:.4f} vs {k['baseline_auc']:.4f} for a majority-class "
        f"baseline. Top features by permutation importance: {top3}; agency and complaint type "
        f"shuffled together drop AUC by {k['pair_drop']:.4f}.",
        "",
        "| | |",
        "|---|---|",
        f"| {figs[0]} | {figs[1]} |",
        f"| {figs[2]} | {figs[3]} |",
        "",
        "Reproduce: `python analysis/survival.py`, `python analysis/stats_tests.py`, "
        "`python analysis/prediction.py`, then `python analysis/summary.py`.",
        END,
    ])


def update_readme(section):
    text = README.read_text(encoding="utf-8")
    if START in text and END in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + section + after
    else:
        # First run: place it just before the Data section.
        text = text.replace("\n## Data\n", "\n" + section + "\n\n---\n\n## Data\n", 1)
    README.write_text(text, encoding="utf-8")
    print(f"updated {README.name} (Advanced Analysis section)")


def resume_bullets(k):
    bias = k["biggest_bias"][0]
    f1, f2, f3 = (f for f, _ in k["top3_features"])
    return [
        f"Applied survival analysis (Kaplan-Meier, Cox, log-rank) to {k['rows_used']:,} NYC 311 "
        f"requests, treating {k['censored']:,} still-open requests as censored rather than "
        f"dropping them, and showed that including them raised one agency's median "
        f"resolution time by {bias['difference_pct']:.2f}% ({fmt_h(bias['median_closed_only'])} h "
        f"to {fmt_h(bias['km_median'])} h).",
        ("Showed the handling agency drives resolution time" if k["agency_largest_effect"]
         else "Compared agency, borough and season effects on resolution time")
        + f" (Kruskal-Wallis epsilon-squared "
        f"{k['eps']['agency']:.4f} vs {k['eps']['season']:.4f} for season and "
        f"{k['eps']['borough']:.4f} for borough) and built a leakage-free "
        f"{k['best_model'].lower()} model predicting 7-day closure with ROC AUC "
        f"{k['best_auc']:.4f} vs {k['baseline_auc']:.4f} for a baseline, on a time-based "
        f"train/test split; top features: {f1}, {f2}, {f3}.",
    ]


def print_summary(k):
    line = "=" * 72
    print(f"\n{line}\nRESUME-READY NUMBERS (from results/data/*.json)\n{line}")
    print(f"Censored (still-open) requests : {k['censored']:,} of {k['rows_used']:,} used "
          f"({k['pct_censored']:.2f}%)")
    print(f"Overall median, closed only    : {fmt_h(k['overall_closed_only'])} h")
    print(f"Overall median, Kaplan-Meier   : {fmt_h(k['overall_km'])} h "
          f"(95% CI {fmt_h(k['overall_km_ci'][0])} - {fmt_h(k['overall_km_ci'][1])})")
    print("Kaplan-Meier medians, top 8    : "
          + ", ".join(f"{a} {fmt_h(m)} h" for a, m, _, _ in k["top8_km"]))
    for r in k["biggest_bias"]:
        print(f"Largest bias                   : {r['agency']} {fmt_h(r['median_closed_only'])} h "
              f"-> {fmt_h(r['km_median'])} h ({r['difference_pct']:+.2f}%)")
    print(f"Effect sizes (epsilon-squared) : agency {k['eps']['agency']:.6f}, season "
          f"{k['eps']['season']:.6f}, borough {k['eps']['borough']:.6f}")
    print(f"Best model ROC AUC vs baseline : {k['best_model']} {k['best_auc']:.4f} vs "
          f"{k['baseline_auc']:.4f}")
    print("Top 3 features (AUC drop)      : "
          + ", ".join(f"{f} {d:.4f}" for f, d in k["top3_features"]))
    print(f"\n{line}\nSUGGESTED RESUME BULLETS\n{line}")
    for b in resume_bullets(k):
        print(f"- {b}\n")


def main():
    results_md.render()
    k = key_numbers()
    update_readme(readme_section(k))
    print_summary(k)


if __name__ == "__main__":
    main()
