"""Write the README's "Demand Forecasting" section and the resume bullets (Phase 5).

Run:  python forecast/write_summary.py      (seconds; run Phases 1-4 first)

Like analysis/summary.py, the section sits between two marker comments in
README.md and is regenerated from results/forecast/data/*.json, so every number
in it matches the results. The resume bullets are written to
results/forecast/resume_bullets.md and printed.
"""
import fc_common as fc
from results_md import table

README = fc.PROJECT_ROOT / "README.md"
START = "<!-- DEMAND-FORECASTING:START (generated by forecast/write_summary.py; edit that script, not this text) -->"
END = "<!-- DEMAND-FORECASTING:END -->"
SHORT = {"naive": "Naive (tomorrow = today)", "seasonal_naive": "Seasonal naive (same weekday last week)",
         "weekday_avg_4wk": "4-week same-weekday average", "holt_winters": "Holt-Winters",
         "gradient_boosting": "Gradient boosting"}


def load():
    p1, p2, p3, p4 = (fc.load_json(f) for f in ("phase1_data.json", "phase2_baselines.json",
                                                "phase3_models.json", "phase4_agencies.json"))
    m3 = {(r["variant"], r["split"], r["model"]): r for r in p3["metrics"]}
    m4 = {(r["variant"], r["split"], r["series"], r["model"]): r for r in p4["metrics"]}
    best = p3["best_model"]
    k = {
        "p1": p1, "p2": p2, "p3": p3, "p4": p4, "m3": m3, "m4": m4, "best": best,
        "best_val": m3[("as_recorded", "validation", best)],
        "best_test": m3[("as_recorded", "test", best)],
        "test_winner": min((r for r in p3["metrics"] if r["variant"] == "as_recorded" and r["split"] == "test"),
                           key=lambda r: r["mae"]),
        "cov": p3["interval_coverage"],
        "staff": {a: p4["per_agency"][f"as_recorded/{a}"]["staffing"] for a in p4["ranking"]},
        "tot": p1["series_summary"][fc.TOTAL],
    }
    return k


def readme_section(k):
    p1, p2, p3, p4, m3, m4 = k["p1"], k["p2"], k["p3"], k["p4"], k["m3"], k["m4"]
    best, bv, bt_, win, tot = k["best"], k["best_val"], k["best_test"], k["test_winner"], k["tot"]
    cov_v, cov_t = k["cov"]["as_recorded/validation"], k["cov"]["as_recorded/test"]
    comp = [[SHORT[m] + (" (chosen)" if m == best else ""), f"{m3[('as_recorded', 'validation', m)]['mae']:,.0f}",
             f"{m3[('as_recorded', 'test', m)]['mae']:,.0f}", f"{m3[('as_recorded', 'test', m)]['rmse']:,.0f}",
             f"{m3[('as_recorded', 'test', m)]['mape']:.1f}%", f"{m3[('as_recorded', 'test', m)]['mae_improvement_pct']:+.1f}%"]
            for m in p3["order"]]
    agencies = []
    for a in p4["ranking"]:
        c = p4["chosen"][f"as_recorded/{a}"]
        t = m4[("as_recorded", "test", a, c)]
        s = k["staff"][a]
        agencies.append([a, SHORT[c], f"{t['mape']:.1f}%", f"{t['mae_improvement_pct']:+.1f}%",
                         f"{s['forecast']['short_days_pct']:.0f}%", f"{s['p90']['short_days_pct']:.0f}%"])
    excl = m3[("excl_hotspots", "test", best)]
    staff_f = [s["forecast"]["short_days_pct"] for s in k["staff"].values()]
    staff_p = [s["p90"]["short_days_pct"] for s in k["staff"].values()]
    episodes = len(p1["outlier_episodes_total"])
    return "\n".join([
        START,
        "## Demand Forecasting",
        "",
        "Framed like supply-chain demand planning: forecast **daily 311 request volume 14 days ahead**, citywide and "
        "for the 5 busiest agencies, and turn the forecast into a staffing plan the way a planner turns a demand "
        "forecast into inventory. Code in [`forecast/`](forecast/); every number in "
        "[`results/forecast/forecast.md`](results/forecast/forecast.md); build log in [`BUILD_LOG.md`](BUILD_LOG.md); "
        "interactive version on the dashboard's **Forecast** page.",
        "",
        "**Approach.**",
        "",
        f"- **Data** ([`sql/forecast/`](sql/forecast/)): {p1['calendar']['days_in_series']} daily counts, built on a "
        f"full calendar so a missing day can't hide. No missing or partial days and no outages. {tot['n_outlier_days']} "
        f"outlier days in {episodes} episodes (holidays, a cold snap, the December snow, a batch load) were kept, "
        f"because a forecast should be judged on them. One Bronx location filing bursts of noise complaints "
        f"({tot['hotspot_pct']:.1f}% of the year) is measured with a same-day rule, so every result is also "
        f"reported without it.",
        f"- **Baselines:** naive, seasonal naive (same weekday last week) and a 4-week same-weekday average.",
        f"- **Models:** Holt-Winters (statsmodels; {p3['chosen_settings']['holt_winters']}) and gradient boosting "
        f"(scikit-learn; {p3['chosen_settings']['gradient_boosting']}) with day of week, month, US federal holidays, "
        f"`lag_7`, `lag_14` and a 7-day mean. It uses a *direct* multi-step strategy: one model predicts day t+h from "
        f"what was known on day t, so its own predictions are never fed back in.",
        "",
        f"**Backtest design.** Rolling origin: at each weekly cutoff a model gets only the days up to the cutoff and "
        f"forecasts the next {p2['horizon']}. {len(p2['validation_cutoffs'])} **validation** cutoffs "
        f"({p2['validation_cutoffs'][0]} to {p2['validation_cutoffs'][-1]}) are used to tune settings and pick the "
        f"model; {len(p2['test_cutoffs'])} **test** cutoffs ({p2['test_cutoffs'][0]} to {p2['test_cutoffs'][-1]}, "
        f"the last 10 weeks of 2025) are only reported. The engine cuts the data at the cutoff before the model runs, "
        f"and tests check that rewriting every value after the cutoff doesn't change a forecast.",
        "",
        "**Results, citywide (MAE = average miss in requests per day):**",
        "",
        table(["Model", "Validation MAE", "Test MAE", "Test RMSE", "Test MAPE", "Test MAE vs seasonal naive"], comp),
        "",
        f"- {SHORT[best]} won validation ({bv['mae_improvement_pct']:+.1f}% MAE vs seasonal naive) and was chosen. "
        f"On test it stayed ahead of seasonal naive ({bt_['mae_improvement_pct']:+.1f}%), but the "
        f"**{SHORT[win['model']].lower()} was best on test** ({win['mae_improvement_pct']:+.1f}%). The validation "
        f"weeks were calm, while the test weeks had the bursts, Thanksgiving, the snow and Christmas. Single lags "
        f"copied events into the next week; averaging four weeks diluted them. Nothing was re-tuned after seeing this.",
        f"- Without the burst location, the chosen model's test MAE falls to {excl['mae']:,.0f} and MAPE to "
        f"{excl['mape']:.1f}%.",
        f"- **80% prediction intervals** (from the model's own past errors, using only windows finished before each "
        f"cutoff) covered {cov_v['coverage_pct']:.1f}% of validation days but only {cov_t['coverage_pct']:.1f}% of test "
        f"days. They were calibrated on calm months, so they were far too narrow for December.",
        "",
        "**Per agency** (approach picked on each agency's own validation windows; easiest to hardest):",
        "",
        table(["Agency", "Chosen", "Test MAPE", "Test MAE vs seasonal naive", "Short days: roster to forecast",
               "Short days: roster to P90"], agencies),
        "",
        f"{p4['ranking'][0]} is easiest because its demand follows the working week. {p4['ranking'][-1]} is hardest: "
        f"the December snow drives most of its error. Rostering to the top of the 80% interval (P90, the staffing "
        f"version of safety stock) cut short-staffed days from {min(staff_f):.0f}-{max(staff_f):.0f}% to "
        f"{min(staff_p):.0f}-{max(staff_p):.0f}%. That is still above the 10% a P90 plan should give, for the same "
        f"reason the intervals under-covered.",
        "",
        "| | |",
        "|---|---|",
        "| <img src=\"results/forecast/figures/f3a_best_model_intervals.png\" alt=\"Forecast vs actual with 80% "
        "intervals\" width=\"100%\"> | <img src=\"results/forecast/figures/f4a_agency_mape.png\" alt=\"Per-agency "
        "forecast error\" width=\"100%\"> |",
        "",
        "**Limitations.**",
        "",
        "- **One year of data.** Each season and each holiday happens once, so yearly seasonality (HPD's heating "
        "season, DEP's summer) can't be learned, and holiday effects are averaged across very different holidays.",
        "- **No external drivers.** No weather, events or school calendar. Snow, heavy rain and heat caused the "
        "biggest misses, and only a forecast of the weather itself could anticipate them.",
        f"- **Short test period.** {len(p2['test_cutoffs'])} overlapping 14-day windows in one unusual stretch of the "
        "year. The results show how the methods behave in a volatile period, not a stable long-run accuracy.",
        "- **Requests, not workload.** A request's effort varies by type, and there's no data on requests handled per "
        "staff shift, so staffing is expressed in requests per day.",
        "",
        "**What I'd do next.**",
        "",
        "1. Add 2023-2024 data from the same API, so the models can learn the heating season, summer and each holiday.",
        "2. Add weather forecasts (snow, rain, temperature) as features: they are known in advance, like holidays.",
        "3. Make lag features robust: use the median of the last 4 same weekdays instead of single lags, so one event "
        "isn't copied forward.",
        "4. Choose models on a validation period that includes volatile weeks (needs the extra years), and consider "
        "an average of the 4-week baseline and the models.",
        "5. Recalibrate the intervals by season, or use conformal prediction over a longer history, and track their "
        "coverage every week.",
        "",
        "Reproduce: `python forecast/daily_series.py`, `python forecast/baselines.py`, "
        "`python forecast/evaluate_models.py`, `python forecast/agencies.py`, "
        "`python forecast/build_forecast_app_data.py`, then `python forecast/write_summary.py`.",
        END,
    ])


def update_readme(section):
    text = README.read_text(encoding="utf-8")
    if START in text and END in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + section + after
    else:
        # First run: place it right after the Advanced Analysis section.
        anchor = "<!-- ADVANCED-ANALYSIS:END -->"
        assert anchor in text, "README has no Advanced Analysis section to place the forecast section after"
        text = text.replace(anchor, anchor + "\n\n---\n\n" + section, 1)
    README.write_text(text, encoding="utf-8")
    print(f"updated {README.name} (Demand Forecasting section)")


def resume_bullets(k):
    p2, p4, best, bt_, bv = k["p2"], k["p4"], k["best"], k["best_test"], k["best_val"]
    n_test = len(p2["test_cutoffs"])
    staff_f = [s["forecast"]["short_days_pct"] for s in k["staff"].values()]
    staff_p = [s["p90"]["short_days_pct"] for s in k["staff"].values()]
    win = k["test_winner"]
    tot = k["tot"]
    return [
        f"Forecasted daily NYC 311 request volume {p2['horizon']} days ahead with {SHORT[best].lower()} "
        f"(calendar, federal-holiday and lag features), reducing MAE {bv['mae_improvement_pct']:.1f}% vs. a "
        f"seasonal-naive baseline on {len(p2['validation_cutoffs'])} validation windows and "
        f"{bt_['mae_improvement_pct']:.1f}% on {n_test} held-out rolling-origin test windows; documented that a "
        f"{SHORT[win['model']].lower()} did better on the volatile test period ({win['mae_improvement_pct']:.1f}%).",
        f"Built leakage-free forecasts for NYC's {len(p4['ranking'])} busiest 311 agencies and turned 80% prediction "
        f"intervals into P90 staffing plans, cutting backtested short-staffed days from "
        f"{min(staff_f):.0f}-{max(staff_f):.0f}% to {min(staff_p):.0f}-{max(staff_p):.0f}%; found a single-location "
        f"filing burst ({tot['hotspot_requests']:,} requests) whose removal cut outlier days from "
        f"{tot['n_outlier_days']} to {tot['n_outlier_days_excl_hotspots']}.",
    ]


def main():
    k = load()
    update_readme(readme_section(k))
    bullets = resume_bullets(k)
    path = fc.OUT_DIR / "resume_bullets.md"
    path.write_text("# Resume bullets (generated by forecast/write_summary.py)\n\n" +
                    "\n".join(f"- {b}" for b in bullets) + "\n", encoding="utf-8")
    print(f"saved {path.relative_to(fc.PROJECT_ROOT)}\n")
    for b in bullets:
        print(f"- {b}\n")


if __name__ == "__main__":
    main()
